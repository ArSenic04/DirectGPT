import type { RequestStatus } from '../../../shared/types';

const LABELS: Record<RequestStatus, string> = {
  generating: 'Generating…',
  pending: 'Pending review',
  accepted: 'Accepted',
  rejected: 'Rejected',
  conflicted: 'Conflict',
  reverted: 'Reverted',
  failed: 'Failed',
};

export function StatusBadge({ status }: { status: RequestStatus }) {
  return (
    <span className={`cdg-status cdg-status-${status}`} data-testid="status-badge" data-status={status}>
      {LABELS[status]}
    </span>
  );
}

export function MockBadge() {
  return (
    <span className="cdg-mock-badge" title="Generated by the built-in deterministic MOCK provider, not a real language model">
      MOCK
    </span>
  );
}

export function formatTime(t: number | undefined): string {
  if (t === undefined) return '';
  return new Date(t).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' });
}
